'use strict';

const path = require('path');
const fsExtra = require('fs-extra');

/**
 * Generates a Spring Boot 3 version layer from verified transforms:
 *
 *   CompatTransform.java       one rewrite (data)                — fixed
 *   CompatVersion.java         the transforms a version introduced — fixed
 *   CompatEngine.java          applies transforms to Jackson trees — fixed
 *   CompatResponseAdvice.java  old clients get the old response shape — fixed
 *   CompatRequestAdvice.java   old request shapes are upgraded on the way in — fixed
 *   ApiVersion_<v>.java        this change's transforms           — generated per version
 *
 * The fixed files implement the same rules as shim/transforms.js, where the
 * CLI verified every transform before generating anything. Re-running for a
 * later version adds another ApiVersion_<v> class; the runtime applies every
 * version newer than the one the client asked for, newest first.
 *
 * A client's version comes from a request header (X-API-Version by default).
 * Clients that send none are treated as the version before the oldest
 * change: existing integrations keep their shape without changing anything.
 */
async function generateSpring(shim, { dir, pkg, header, version, basePath }) {
  if (!/^[a-zA-Z_][\w]*(\.[a-zA-Z_][\w]*)*$/.test(pkg)) throw new Error(`--package "${pkg}" is not a Java package name`);
  const out = path.join(dir, ...pkg.split('.'));
  const files = {
    'CompatTransform.java': transformClass(pkg),
    'CompatVersion.java': versionInterface(pkg),
    'CompatEngine.java': engineClass(pkg),
    'CompatResponseAdvice.java': responseAdvice(pkg, header, basePath),
    'CompatRequestAdvice.java': requestAdvice(pkg, header, basePath),
    [`${versionClassName(version)}.java`]: versionClass(pkg, version, shim.transforms),
  };
  const written = [];
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(out, name);
    await fsExtra.outputFile(file, content);
    written.push(file);
  }
  return written;
}

function versionClassName(version) {
  return `ApiVersion_${String(version).replace(/[^A-Za-z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'next'}`;
}

const j = (s) => JSON.stringify(s === undefined ? null : s);
const header = (pkg) => `// Generated by SpecShield (specshield fix --spring). Safe to edit; re-running overwrites it.\npackage ${pkg};\n`;

// ─── per-version transforms ─────────────────────────────────────────────────

function versionClass(pkg, version, transforms) {
  // Renames and enum mappings are inferred from the spec diff (a field gone
  // and a similar one added); say so where a reviewer will read it.
  const lines = transforms.map((t) => `            ${t.kind === 'rename' || t.kind === 'enum' ? '/* inferred rename — check */ ' : ''}${call(t)}`);
  return `${header(pkg)}
import java.util.List;
import org.springframework.stereotype.Component;

/**
 * What changed in API version ${version}, as rewrites that give clients on an
 * older version the shape they were built against. Each one was checked by
 * SpecShield against the old schema on sample payloads.
 */
@Component
public class ${versionClassName(version)} implements CompatVersion {

    @Override
    public String version() {
        return ${j(String(version))};
    }

    @Override
    public List<CompatTransform> transforms() {
        return List.of(
${lines.join(',\n')}
        );
    }
}
`;
}

function call(t) {
  // A value rewrite of array elements (field null) addresses the array and
  // uses the field "[]": "rewrite each element".
  const elements = (t.kind === 'convert' || t.kind === 'enum') && t.field === null;
  const steps = elements ? t.at.slice(0, -1) : t.at;
  const field = elements ? '[]' : t.field;
  t = { ...t, field };
  const at = `CompatTransform.steps(${steps.map((s) => (s.prop !== undefined ? j(s.prop) : s.items ? '"[]"' : '"{}"')).join(', ')})`;
  const head = `${j(t.method)}, ${j(t.path)}, ${j(t.code)}, ${at}`;
  const side = t.side === 'response' ? 'response' : 'request';
  switch (t.kind) {
    case 'rename': return `CompatTransform.${side}Rename(${head}, ${j(t.from)}, ${j(t.to)})`;
    case 'convert': return `CompatTransform.${side}Convert(${head}, ${j(t.field)}, ${j(t.to)})`;
    case 'enum': return `CompatTransform.${side}Enum(${head}, ${j(t.field)}, ${j(JSON.stringify(t.from))}, ${j(JSON.stringify(t.to))})`;
    case 'default': return `CompatTransform.${side}Default(${head}, ${j(t.field)}, ${j(JSON.stringify(t.value))})`;
    case 'unwrap': return `CompatTransform.${side}Unwrap(${head}, ${j(t.property)})`;
    default: throw new Error(`unknown transform ${t.kind}`);
  }
}

// ─── fixed runtime ──────────────────────────────────────────────────────────

function transformClass(pkg) {
  return `${header(pkg)}
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.util.List;

/**
 * One JSON rewrite for one operation. {@code at} addresses the object (or
 * array) it acts on from the body root: a property name, "[]" for every
 * array element, "{}" for every map value. A value rewrite with
 * {@code field} "[]" rewrites the elements of the array at {@code at}.
 */
public record CompatTransform(
        String method, String path, String status, boolean response, Kind kind,
        List<String> at, String from, String to, String field, JsonNode fromValue, JsonNode toValue) {

    public enum Kind { RENAME, CONVERT, ENUM, DEFAULT, UNWRAP }

    private static final ObjectMapper JSON = new ObjectMapper();

    public static List<String> steps(String... steps) {
        return List.of(steps);
    }

    public static CompatTransform responseRename(String m, String p, String s, List<String> at, String from, String to) {
        return new CompatTransform(m, p, s, true, Kind.RENAME, at, from, to, null, null, null);
    }

    public static CompatTransform requestRename(String m, String p, String s, List<String> at, String from, String to) {
        return new CompatTransform(m, p, s, false, Kind.RENAME, at, from, to, null, null, null);
    }

    public static CompatTransform responseConvert(String m, String p, String s, List<String> at, String field, String toType) {
        return new CompatTransform(m, p, s, true, Kind.CONVERT, at, null, toType, field, null, null);
    }

    public static CompatTransform requestConvert(String m, String p, String s, List<String> at, String field, String toType) {
        return new CompatTransform(m, p, s, false, Kind.CONVERT, at, null, toType, field, null, null);
    }

    public static CompatTransform responseEnum(String m, String p, String s, List<String> at, String field, String from, String to) {
        return new CompatTransform(m, p, s, true, Kind.ENUM, at, null, null, field, json(from), json(to));
    }

    public static CompatTransform requestEnum(String m, String p, String s, List<String> at, String field, String from, String to) {
        return new CompatTransform(m, p, s, false, Kind.ENUM, at, null, null, field, json(from), json(to));
    }

    public static CompatTransform requestDefault(String m, String p, String s, List<String> at, String field, String value) {
        return new CompatTransform(m, p, s, false, Kind.DEFAULT, at, null, null, field, null, json(value));
    }

    public static CompatTransform responseUnwrap(String m, String p, String s, List<String> at, String property) {
        return new CompatTransform(m, p, s, true, Kind.UNWRAP, at, property, null, null, null, null);
    }

    private static JsonNode json(String literal) {
        try {
            return JSON.readTree(literal);
        } catch (Exception e) {
            throw new IllegalArgumentException("Invalid JSON literal " + literal, e);
        }
    }
}
`;
}

function versionInterface(pkg) {
  return `${header(pkg)}
import java.util.List;

/** The rewrites one API version introduced. Implementations are Spring beans. */
public interface CompatVersion {

    /** The version that introduced these changes, e.g. "2.0.0" or "2026-11-01". */
    String version();

    List<CompatTransform> transforms();
}
`;
}

function engineClass(pkg) {
  return `${header(pkg)}
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.BooleanNode;
import com.fasterxml.jackson.databind.node.JsonNodeFactory;
import com.fasterxml.jackson.databind.node.ObjectNode;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.function.Consumer;
import java.util.function.UnaryOperator;
import java.util.regex.Pattern;
import org.springframework.stereotype.Component;
import org.springframework.util.AntPathMatcher;

/**
 * Applies version transforms to Jackson trees. The rules match SpecShield's
 * own implementation, where every transform was verified:
 * responses are rewritten from the newest version down to the client's,
 * requests from the client's version up; unwrap runs first; on responses
 * renames run before value rewrites, on requests after them.
 */
@Component
public class CompatEngine {

    private static final Pattern NUMBER = Pattern.compile("\\\\s*-?\\\\d+(\\\\.\\\\d+)?([eE][+-]?\\\\d+)?\\\\s*");
    private final List<CompatVersion> versions;
    private final AntPathMatcher paths = new AntPathMatcher();

    public CompatEngine(List<CompatVersion> versions) {
        this.versions = new ArrayList<>(versions);
        this.versions.sort(Comparator.comparing(CompatVersion::version, CompatEngine::compareVersions));
    }

    /** The version a client that sends no version header is on: the one before the oldest change. */
    public String oldestVersion() {
        return versions.isEmpty() ? null : versions.get(0).version();
    }

    public JsonNode response(String clientVersion, String method, String path, int status, JsonNode body) {
        JsonNode root = body;
        for (int i = versions.size() - 1; i >= 0; i--) {
            CompatVersion v = versions.get(i);
            if (!olderThan(clientVersion, v.version())) continue;
            root = apply(root, select(v, true, method, path, status));
        }
        return root;
    }

    public JsonNode request(String clientVersion, String method, String path, JsonNode body) {
        JsonNode root = body;
        for (CompatVersion v : versions) {
            if (!olderThan(clientVersion, v.version())) continue;
            root = apply(root, select(v, false, method, path, -1));
        }
        return root;
    }

    /** True when there is anything to do for this request at all. */
    public boolean applies(String clientVersion, boolean response, String method, String path) {
        for (CompatVersion v : versions) {
            if (!olderThan(clientVersion, v.version())) continue;
            for (CompatTransform t : v.transforms()) {
                if (t.response() == response && t.method().equalsIgnoreCase(method) && paths.match(t.path(), path)) return true;
            }
        }
        return false;
    }

    private List<CompatTransform> select(CompatVersion v, boolean response, String method, String path, int status) {
        List<CompatTransform> out = new ArrayList<>();
        for (CompatTransform t : v.transforms()) {
            if (t.response() != response || !t.method().equalsIgnoreCase(method) || !paths.match(t.path(), path)) continue;
            if (response && t.status() != null && !t.status().equals(String.valueOf(status))) continue;
            out.add(t);
        }
        out.sort(Comparator.comparingInt(t -> rank(t)));
        return out;
    }

    private static int rank(CompatTransform t) {
        return switch (t.kind()) {
            case UNWRAP -> 0;
            case RENAME -> t.response() ? 1 : 3;
            case DEFAULT -> t.response() ? 2 : 4;
            case CONVERT -> t.response() ? 3 : 1;
            case ENUM -> t.response() ? 4 : 2;
        };
    }

    JsonNode apply(JsonNode root, List<CompatTransform> transforms) {
        for (CompatTransform t : transforms) {
            if (t.kind() == CompatTransform.Kind.UNWRAP) {
                if (root instanceof ObjectNode o && o.has(t.from())) root = o.get(t.from());
                continue;
            }
            forEachAt(root, t.at(), 0, node -> applyOne(node, t));
        }
        return root;
    }

    private void forEachAt(JsonNode node, List<String> steps, int i, Consumer<JsonNode> fn) {
        if (node == null) return;
        if (i == steps.size()) { fn.accept(node); return; }
        String s = steps.get(i);
        if ("[]".equals(s)) {
            if (node instanceof ArrayNode a) for (JsonNode el : a) forEachAt(el, steps, i + 1, fn);
        } else if ("{}".equals(s)) {
            if (node instanceof ObjectNode o) o.elements().forEachRemaining(v -> forEachAt(v, steps, i + 1, fn));
        } else if (node instanceof ObjectNode o && o.has(s)) {
            forEachAt(o.get(s), steps, i + 1, fn);
        }
    }

    private void applyOne(JsonNode node, CompatTransform t) {
        switch (t.kind()) {
            case RENAME -> {
                if (node instanceof ObjectNode o && o.has(t.from()) && !o.has(t.to())) {
                    o.set(t.to(), o.get(t.from()));
                    o.remove(t.from());
                }
            }
            case DEFAULT -> {
                if (node instanceof ObjectNode o && !o.has(t.field())) o.set(t.field(), t.toValue().deepCopy());
            }
            default -> {
                UnaryOperator<JsonNode> rewrite = v -> t.kind() == CompatTransform.Kind.ENUM
                        ? (v.equals(t.fromValue()) ? t.toValue().deepCopy() : v)
                        : convert(v, t.to());
                if ("[]".equals(t.field())) {
                    if (node instanceof ArrayNode a) for (int k = 0; k < a.size(); k++) a.set(k, rewrite.apply(a.get(k)));
                } else if (node instanceof ObjectNode o && o.has(t.field())) {
                    o.set(t.field(), rewrite.apply(o.get(t.field())));
                }
            }
        }
    }

    /** Converts a JSON scalar; leaves it untouched when it has no faithful form in the target type. */
    static JsonNode convert(JsonNode v, String to) {
        if (v == null || v.isNull()) return v;
        JsonNodeFactory f = JsonNodeFactory.instance;
        switch (to) {
            case "string":
                if (v.isTextual()) return v;
                // 12.0 → "12", like JavaScript's String(12.0) where the transform was verified.
                return f.textNode(v.isNumber() ? v.decimalValue().stripTrailingZeros().toPlainString() : v.asText());
            case "boolean":
                if (v.isBoolean()) return v;
                if (v.isTextual() && "true".equals(v.asText()) || v.isNumber() && v.decimalValue().compareTo(BigDecimal.ONE) == 0) return BooleanNode.TRUE;
                if (v.isTextual() && "false".equals(v.asText()) || v.isNumber() && v.decimalValue().signum() == 0) return BooleanNode.FALSE;
                return v;
            default:
                BigDecimal n;
                if (v.isNumber()) n = v.decimalValue();
                else if (v.isTextual() && NUMBER.matcher(v.asText()).matches()) n = new BigDecimal(v.asText().trim());
                else return v;
                if ("integer".equals(to)) {
                    BigDecimal s = n.stripTrailingZeros();
                    return s.scale() > 0 ? v : f.numberNode(s.toBigIntegerExact());
                }
                return f.numberNode(n);
        }
    }

    boolean olderThan(String client, String version) {
        return client == null || compareVersions(client, version) < 0;
    }

    /** "1.10.0" > "1.9.2"; dates "2026-11-01" compare as numbers too. */
    static int compareVersions(String a, String b) {
        String[] x = a.trim().replaceFirst("^[vV]", "").split("[^A-Za-z0-9]+");
        String[] y = b.trim().replaceFirst("^[vV]", "").split("[^A-Za-z0-9]+");
        for (int i = 0; i < Math.max(x.length, y.length); i++) {
            String p = i < x.length ? x[i] : "0";
            String q = i < y.length ? y[i] : "0";
            int c = p.matches("\\\\d+") && q.matches("\\\\d+")
                    ? new java.math.BigInteger(p).compareTo(new java.math.BigInteger(q))
                    : p.compareTo(q);
            if (c != 0) return c;
        }
        return 0;
    }
}
`;
}

function responseAdvice(pkg, headerName, basePath) {
  return `${header(pkg)}
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.servlet.http.HttpServletRequest;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.MethodParameter;
import org.springframework.http.MediaType;
import org.springframework.http.converter.HttpMessageConverter;
import org.springframework.http.converter.json.AbstractJackson2HttpMessageConverter;
import org.springframework.http.server.ServerHttpRequest;
import org.springframework.http.server.ServerHttpResponse;
import org.springframework.http.server.ServletServerHttpRequest;
import org.springframework.http.server.ServletServerHttpResponse;
import org.springframework.web.bind.annotation.ControllerAdvice;
import org.springframework.web.servlet.mvc.method.annotation.ResponseBodyAdvice;

/** Rewrites JSON responses into the shape of the version the client asked for. */
@ControllerAdvice
public class CompatResponseAdvice implements ResponseBodyAdvice<Object> {

    private final CompatEngine engine;
    private final ObjectMapper mapper;
    private final String header;
    private final String basePath;

    public CompatResponseAdvice(CompatEngine engine, ObjectMapper mapper,
                                @Value("\${specshield.compat.header:${headerName}}") String header,
                                @Value("\${specshield.compat.base-path:${basePath}}") String basePath) {
        this.engine = engine;
        this.mapper = mapper;
        this.header = header;
        this.basePath = basePath;
    }

    @Override
    public boolean supports(MethodParameter returnType, Class<? extends HttpMessageConverter<?>> converterType) {
        return AbstractJackson2HttpMessageConverter.class.isAssignableFrom(converterType);
    }

    @Override
    public Object beforeBodyWrite(Object body, MethodParameter returnType, MediaType contentType,
                                  Class<? extends HttpMessageConverter<?>> converterType,
                                  ServerHttpRequest request, ServerHttpResponse response) {
        if (body == null || !(request instanceof ServletServerHttpRequest req)) return body;
        HttpServletRequest http = req.getServletRequest();
        String client = clientVersion(http);
        String path = apiPath(http);
        if (!engine.applies(client, true, http.getMethod(), path)) return body;
        int status = response instanceof ServletServerHttpResponse r ? r.getServletResponse().getStatus() : 200;
        JsonNode tree = mapper.valueToTree(body);
        return engine.response(client, http.getMethod(), path, status, tree);
    }

    private String clientVersion(HttpServletRequest http) {
        String v = http.getHeader(header);
        return v == null || v.isBlank() ? null : v.trim();
    }

    private String apiPath(HttpServletRequest http) {
        String p = http.getRequestURI().substring(http.getContextPath().length());
        return !basePath.isEmpty() && p.startsWith(basePath) ? p.substring(basePath.length()) : p;
    }
}
`;
}

function requestAdvice(pkg, headerName, basePath) {
  return `${header(pkg)}
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.servlet.http.HttpServletRequest;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.lang.reflect.Type;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.MethodParameter;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpInputMessage;
import org.springframework.http.converter.HttpMessageConverter;
import org.springframework.http.converter.json.AbstractJackson2HttpMessageConverter;
import org.springframework.web.bind.annotation.ControllerAdvice;
import org.springframework.web.context.request.RequestContextHolder;
import org.springframework.web.context.request.ServletRequestAttributes;
import org.springframework.web.servlet.mvc.method.annotation.RequestBodyAdviceAdapter;

/** Upgrades JSON request bodies sent in an older version's shape before Spring binds them. */
@ControllerAdvice
public class CompatRequestAdvice extends RequestBodyAdviceAdapter {

    private final CompatEngine engine;
    private final ObjectMapper mapper;
    private final String header;
    private final String basePath;

    public CompatRequestAdvice(CompatEngine engine, ObjectMapper mapper,
                               @Value("\${specshield.compat.header:${headerName}}") String header,
                               @Value("\${specshield.compat.base-path:${basePath}}") String basePath) {
        this.engine = engine;
        this.mapper = mapper;
        this.header = header;
        this.basePath = basePath;
    }

    @Override
    public boolean supports(MethodParameter parameter, Type targetType,
                            Class<? extends HttpMessageConverter<?>> converterType) {
        return AbstractJackson2HttpMessageConverter.class.isAssignableFrom(converterType);
    }

    @Override
    public HttpInputMessage beforeBodyRead(HttpInputMessage input, MethodParameter parameter, Type targetType,
                                           Class<? extends HttpMessageConverter<?>> converterType) throws IOException {
        if (!(RequestContextHolder.getRequestAttributes() instanceof ServletRequestAttributes attrs)) return input;
        HttpServletRequest http = attrs.getRequest();
        String v = http.getHeader(header);
        String client = v == null || v.isBlank() ? null : v.trim();
        String p = http.getRequestURI().substring(http.getContextPath().length());
        String path = !basePath.isEmpty() && p.startsWith(basePath) ? p.substring(basePath.length()) : p;
        if (!engine.applies(client, false, http.getMethod(), path)) return input;

        byte[] raw = input.getBody().readAllBytes();
        if (raw.length == 0) return replay(input.getHeaders(), raw);
        JsonNode tree;
        try {
            tree = mapper.readTree(raw);
        } catch (IOException notJson) {
            return replay(input.getHeaders(), raw);       // let Spring report the bad body as usual
        }
        byte[] upgraded = mapper.writeValueAsBytes(engine.request(client, http.getMethod(), path, tree));
        return replay(input.getHeaders(), upgraded);
    }

    private static HttpInputMessage replay(HttpHeaders original, byte[] body) {
        HttpHeaders headers = new HttpHeaders();
        headers.putAll(original);
        headers.setContentLength(body.length);
        return new HttpInputMessage() {
            @Override
            public InputStream getBody() {
                return new ByteArrayInputStream(body);
            }

            @Override
            public HttpHeaders getHeaders() {
                return headers;
            }
        };
    }
}
`;
}

